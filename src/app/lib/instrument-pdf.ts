import PDFDocument from "pdfkit";
import { execFile } from "node:child_process";
import { randomBytes } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { DossierDocument, DossierSealSummary } from "./instrument";

type PDFDoc = InstanceType<typeof PDFDocument>;

const PAGE_MARGIN = 50;
const CONTENT_WIDTH = 595.28 - PAGE_MARGIN * 2;

function formatDate(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return `${date.toISOString().slice(0, 16).replace("T", " ")} UTC`;
}

function officialRecordLabel(summary: DossierSealSummary): string {
  if (summary.count <= 1) return "first seal of this project";
  const first = summary.firstSealAt
    ? ` — first sealed ${formatDate(summary.firstSealAt)}`
    : "";
  return `${summary.number} of ${summary.count}${first}`;
}

const MONTHS = [
  "January",
  "February",
  "March",
  "April",
  "May",
  "June",
  "July",
  "August",
  "September",
  "October",
  "November",
  "December",
];

function formatLongDate(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return iso;
  return `${date.getUTCDate()} ${
    MONTHS[date.getUTCMonth()]
  } ${date.getUTCFullYear()}`;
}

function drawCover(pdf: PDFDoc, dossier: DossierDocument): void {
  pdf.moveDown(7);
  pdf
    .font("Helvetica-Bold")
    .fontSize(30)
    .fillColor("#1A1A1A")
    .text("Official dossier", { align: "center" });
  pdf.moveDown(0.5);
  pdf
    .font("Helvetica")
    .fontSize(16)
    .fillColor("#666666")
    .text(dossier.certificate.projectName, { align: "center" });
  pdf.moveDown(1.5);
  const centerX = PAGE_MARGIN + CONTENT_WIDTH / 2;
  pdf
    .moveTo(centerX - 90, pdf.y)
    .lineTo(centerX + 90, pdf.y)
    .strokeColor("#1A1A1A")
    .lineWidth(0.75)
    .stroke();
  pdf.moveDown(1.5);
  pdf.font("Helvetica").fontSize(11).fillColor("#666666");
  pdf.text(`Sealed by ${dossier.certificate.authorEmail ?? "unknown author"}`, {
    align: "center",
  });
  pdf.text(formatLongDate(dossier.certificate.sealedAt), { align: "center" });
  pdf.fillColor("#000000");
}

function addFooter(pdf: PDFDoc): void {
  const bottom = pdf.page.height - PAGE_MARGIN - 30;
  pdf.font("Helvetica").fontSize(8).fillColor("#666666");
  pdf.text(
    "Generated by Ideon — verifiable with `node verify-record.mjs <bundle>.json` (included in the dossier archive)",
    PAGE_MARGIN,
    bottom,
    { width: CONTENT_WIDTH, align: "center" },
  );
  pdf.fillColor("#000000");
}

function ensureSpace(pdf: PDFDoc, needed: number): number {
  const limit = pdf.page.height - PAGE_MARGIN - 50;
  if (pdf.y + needed <= limit) return pdf.y;
  addFooter(pdf);
  pdf.addPage();
  return PAGE_MARGIN;
}

function drawTable(
  pdf: PDFDoc,
  columns: { header: string; width: number }[],
  rows: string[][],
): void {
  const drawRow = (cells: string[], bold: boolean) => {
    let maxHeight = 0;
    const heights = cells.map((cell, index) => {
      const height = pdf.heightOfString(cell || " ", {
        width: columns[index].width - 8,
      });
      maxHeight = Math.max(maxHeight, height);
      return height;
    });

    ensureSpace(pdf, maxHeight + 10);

    let x = PAGE_MARGIN;
    pdf.font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(9);
    cells.forEach((cell, index) => {
      pdf.text(cell || " ", x + 4, pdf.y, {
        width: columns[index].width - 8,
        height: heights[index],
      });
      x += columns[index].width;
    });
    pdf.y += maxHeight + 6;
    pdf
      .moveTo(PAGE_MARGIN, pdf.y - 3)
      .lineTo(pdf.page.width - PAGE_MARGIN, pdf.y - 3)
      .lineWidth(0.5)
      .strokeColor("#cccccc")
      .stroke();
  };

  drawRow(
    columns.map((column) => column.header),
    true,
  );
  for (const row of rows) {
    const previousPage = pdf.page;
    drawRow(row, false);
    if (pdf.page !== previousPage) {
      drawRow(
        columns.map((column) => column.header),
        true,
      );
    }
  }
  pdf.moveDown(0.5);
}

function sectionTitle(pdf: PDFDoc, title: string): void {
  ensureSpace(pdf, 60);
  pdf.moveDown(1);
  pdf.font("Helvetica-Bold").fontSize(15).fillColor("#1A1A1A").text(title);
  pdf.fillColor("#000000");
  pdf.moveDown(0.5);
}

function drawBlockList(
  pdf: PDFDoc,
  label: string,
  blocks: { id: string; blockType: string; title: string | null }[],
): void {
  pdf.font("Helvetica-Bold").fontSize(10).text(label);
  if (blocks.length === 0) {
    pdf.font("Helvetica").fontSize(9).fillColor("#666666").text("  none");
    pdf.fillColor("#000000");
    return;
  }
  pdf.font("Helvetica").fontSize(9);
  for (const block of blocks) {
    const title = block.title ? ` — ${block.title}` : "";
    pdf.text(`  ${block.blockType}${title}`);
  }
  pdf.moveDown(0.5);
}

export async function renderDossierPdf(
  dossier: DossierDocument,
  canvasImage?: string,
): Promise<Buffer> {
  const pdf = new PDFDocument({ size: "A4", margin: PAGE_MARGIN });
  const chunks: Buffer[] = [];
  pdf.on("data", (chunk: Buffer) => chunks.push(chunk));
  const finished = new Promise<Buffer>((resolve) => {
    pdf.on("end", () => resolve(Buffer.concat(chunks)));
  });

  // Cover page.
  drawCover(pdf, dossier);

  // Canvas map.
  if (canvasImage) {
    const base64 = canvasImage.replace(/^data:image\/[a-zA-Z]+;base64,/, "");
    const imageBuffer = Buffer.from(base64, "base64");
    try {
      addFooter(pdf);
      pdf.addPage();
      sectionTitle(pdf, "Canvas map");
      pdf.moveDown();
      const availableHeight = pdf.page.height - pdf.y - PAGE_MARGIN - 50;
      pdf.image(imageBuffer, PAGE_MARGIN, pdf.y, {
        fit: [CONTENT_WIDTH, Math.max(availableHeight, 100)],
      });
    } catch {
      pdf.font("Helvetica").fontSize(9).fillColor("#666666");
      pdf.text("Canvas map unreadable — capture ignored.");
      pdf.fillColor("#000000");
    }
  }

  // Certificate.
  addFooter(pdf);
  pdf.addPage();
  sectionTitle(pdf, "Certificate");
  const integrityLabel =
    dossier.certificate.integrity === "verified"
      ? "verified"
      : "BROKEN — the sealed state no longer matches its fingerprint";
  const certRows: [string, string][] = [
    ["Sealed by", dossier.certificate.authorEmail ?? "unknown author"],
    ["Sealed at", formatDate(dossier.certificate.sealedAt)],
    ["Official record", officialRecordLabel(dossier.sealSummary)],
    ["Integrity", integrityLabel],
    ["Modification", "locked against editing"],
  ];
  for (const [label, value] of certRows) {
    pdf.font("Helvetica-Bold").fontSize(10).text(label, {
      continued: true,
      width: 190,
    });
    pdf.font("Helvetica").fontSize(10).text(`  ${value}`);
  }

  // Timeline.
  sectionTitle(pdf, "Timeline");
  drawTable(
    pdf,
    [
      { header: "Date", width: 105 },
      { header: "Actor", width: 130 },
      { header: "Action", width: 95 },
      { header: "Summary", width: CONTENT_WIDTH - 330 },
    ],
    dossier.timeline.map((entry) => [
      formatDate(entry.at),
      entry.actor ?? "—",
      entry.action,
      entry.summary,
    ]),
  );

  // Inventory.
  sectionTitle(pdf, "Sealed state inventory");
  drawTable(
    pdf,
    [
      { header: "Type", width: 120 },
      { header: "Title", width: CONTENT_WIDTH - 120 },
    ],
    dossier.inventory.map((block) => [block.blockType, block.title ?? "—"]),
  );

  // Drift since the previous seal.
  sectionTitle(pdf, "Drift since the previous seal");
  if (
    dossier.delta.added.length === 0 &&
    dossier.delta.modified.length === 0 &&
    dossier.delta.removed.length === 0
  ) {
    pdf
      .font("Helvetica")
      .fontSize(9)
      .fillColor("#666666")
      .text("No drift — first dossier or no changes between the two seals.");
    pdf.fillColor("#000000");
  } else {
    pdf.font("Helvetica-Bold").fontSize(10);
    pdf.text(
      `${dossier.delta.added.length} added · ${dossier.delta.modified.length} modified · ${dossier.delta.removed.length} removed`,
    );
    pdf.moveDown(0.5);
    drawBlockList(pdf, "Added", dossier.delta.added);
    drawBlockList(pdf, "Modified", dossier.delta.modified);
    drawBlockList(pdf, "Removed", dossier.delta.removed);
  }

  addFooter(pdf);
  pdf.end();

  return finished;
}

// Locks the PDF with AES-256 and a random owner password that is never stored: openable and printable by everyone, editable by no one.
export async function lockPdf(pdfBytes: Buffer): Promise<Buffer> {
  const dir = await mkdtemp(join(tmpdir(), "ideon-lock-"));
  const inputPath = join(dir, "in.pdf");
  const outputPath = join(dir, "out.pdf");
  await writeFile(inputPath, pdfBytes);
  try {
    const ownerPassword = randomBytes(32).toString("base64url");
    await new Promise<void>((resolve, reject) => {
      execFile(
        "qpdf",
        [
          "--encrypt",
          "",
          ownerPassword,
          "256",
          "--print=full",
          "--extract=y",
          "--modify=none",
          "--annotate=n",
          "--form=n",
          "--assemble=n",
          "--",
          inputPath,
          outputPath,
        ],
        { maxBuffer: 64 * 1024 * 1024 },
        (error, _stdout, stderr) => {
          // qpdf exits 3 on warnings only: the output file is still valid.
          if (!error || (typeof error.code === "number" && error.code === 3)) {
            resolve();
            return;
          }
          reject(
            new Error(`qpdf encryption failed: ${stderr || error.message}`),
          );
        },
      );
    });
    return await readFile(outputPath);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}
